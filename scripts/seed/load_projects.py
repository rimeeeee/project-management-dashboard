def check_amounts() -> list[str]:
    """넣기 전에 스스로 확인합니다 — 세목 합계와 총사업비, 세목별 집행 ≤ 편성액."""
    bad: list[str] = []
    for p in PROJECTS:
        alloc = {nm: gov + own for nm, gov, own, _ in p["cats"]}
        if sum(alloc.values()) != p["budget"]:
            bad.append(f"{p['name']}: 세목 합계 {sum(alloc.values()):,} ≠ 총사업비 {p['budget']:,}")
        used: dict[str, int] = {}
        for _, _, _, _, _, spends, _ in p["entries"]:
            for nm, amt, _on in spends:
                used[nm] = used.get(nm, 0) + amt
        for nm, amt in used.items():
            if nm not in alloc:
                bad.append(f"{p['name']}: 집행 세목 '{nm}' 이 편성에 없습니다")
            elif amt > alloc[nm]:
                bad.append(f"{p['name']}: '{nm}' 집행 {amt:,} > 편성 {alloc[nm]:,}")
        kpi_names = {k[0] for k in p["kpis"]}
        for _, _, _, _, _, _, kpi in p["entries"]:
            for nm in kpi:
                if nm not in kpi_names:
                    bad.append(f"{p['name']}: 실적 지표 '{nm}' 이 성과지표에 없습니다")
        # 같은 보고 기간에 두 건이 들어가면 안 됩니다 (period_key 가 유일합니다)
        keys = [period_of(p["cycle"], D(p["start"]), D(e[0])).key for e in p["entries"]]
        if len(keys) != len(set(keys)):
            bad.append(f"{p['name']}: 같은 보고 기간에 입력이 두 건 있습니다 {keys}")
    return bad


def build(spec: dict, order: int) -> Project:
    start = D(spec["start"])
    p = Project(
        id=spec["id"], name=spec["name"], agency=spec["agency"],
        start=start, end=D(spec["end"]), budget=spec["budget"],
        cycle=spec["cycle"], folder_url="", account=spec["account"],
        stage=spec["stage"], sort_order=order,
        created_by=WHO, updated_by=WHO,
    )
    for i, (nm, gov, own, basis) in enumerate(spec["cats"]):
        p.categories.append(ProjectCategory(
            name=nm, budget_amount=gov + own, budget_gov=gov, budget_self=own,
            basis=basis, sort_order=i,
        ))
    for i, (nm, stage, done) in enumerate(spec["tasks"]):
        p.tasks.append(ProjectTask(name=nm, done=done, sort_order=i, stage=stage))
    for i, (nm, unit, target) in enumerate(spec["kpis"]):
        p.kpis.append(ProjectKpi(name=nm, unit=unit, target=float(target), sort_order=i))
    notes = list(spec["stage_notes"])[:STAGE_COUNT]
    notes += [""] * (STAGE_COUNT - len(notes))
    for i, note in enumerate(notes):
        p.stage_notes.append(ProjectStageNote(stage_index=i, note=note))
    for i, (text, due, done) in enumerate(spec["todos"]):
        p.todos.append(ProjectTodo(
            id=f"{spec['id']}-t{i}", text=text, due=D(due) if due else None,
            done=done, sort_order=i, created_by=WHO,
        ))
    for on, act, issue, plan, issue_done, spends, kpi in spec["entries"]:
        d = D(on)
        entry = ReportEntry(
            period_key=period_of(spec["cycle"], start, d).key,
            entry_date=d, act=act, issue=issue, plan=plan,
            issue_done=bool(issue_done and issue), entered_by=WHO, updated_by=WHO,
            version=1,
        )
        for i, (nm, amt, spend_on) in enumerate(spends):
            entry.spends.append(EntrySpend(
                category=nm, amount=amt, spend_on=D(spend_on), sort_order=i,
            ))
        for nm, v in kpi.items():
            entry.kpi_values.append(EntryKpiValue(kpi_name=nm, value=float(v)))
        p.entries.append(entry)
    return p


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--replace", action="store_true", help="같은 이름 사업을 지우고 다시 넣습니다")
    ap.add_argument("--only", default="", help="사업 id 만 골라서 (쉼표로 여럿). 예: --only p4")
    ap.add_argument("--yes", action="store_true", help="운영 데이터베이스에서도 묻지 않고 진행")
    args = ap.parse_args()
    only = {s.strip() for s in args.only.split(",") if s.strip()}

    problems = check_amounts()
    if problems:
        print("데이터가 맞지 않아 넣지 않았습니다:")
        for m in problems:
            print("  -", m)
        return 1

    s = get_settings()
    print("데이터베이스:", s.database_url)

    # 운영(PostgreSQL)에서는 사람이 한 번 확인하고 넣습니다.
    # 실제 자료가 들어 있는 곳이라 임의로 만든 사업이 섞이면 곤란합니다.
    if not s.is_sqlite and not args.yes:
        try:
            answer = input("운영 데이터베이스로 보입니다. 넣으려면  넣겠습니다  를 입력하세요: ")
        except EOFError:
            answer = ""
        if answer.strip() != "넣겠습니다":
            print("중단했습니다.")
            return 1

    db = SessionLocal()
    try:
        have = {p.name: p for p in db.query(Project).all()}
        order = db.query(Project).count()
        added = 0
        for spec in PROJECTS:
            if only and spec["id"] not in only:
                continue
            old = have.get(spec["name"])
            at = order
            if old is not None:
                if not args.replace:
                    print(f"건너뜀 (이미 있음): {spec['name']}")
                    continue
                # 목록에서 자리가 바뀌면 헷갈리므로 순서는 그대로 둡니다
                at = old.sort_order
                db.delete(old)
                db.flush()
                print(f"지우고 다시 넣습니다: {spec['name']}")
            if db.get(Project, spec["id"]) is not None:
                print(f"건너뜀 (id 중복): {spec['id']} {spec['name']}")
                continue
            db.add(build(spec, at))
            if old is None:
                order += 1
            added += 1
        db.commit()
        print(f"\n사업 {added}건을 넣었습니다.")

        for p in db.query(Project).order_by(Project.sort_order, Project.id).all():
            spent = sum(sp.amount for e in p.entries for sp in e.spends)
            rate = (spent / p.budget * 100) if p.budget else 0
            print(f"  {p.id}  {p.name[:34]:<34} {p.cycle}  "
                  f"총 {p.budget:>13,}  집행 {spent:>13,} ({rate:4.1f}%)  "
                  f"세목 {len(p.categories)} · 과제 {len(p.tasks)} · 지표 {len(p.kpis)} · 입력 {len(p.entries)}")
    finally:
        db.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
